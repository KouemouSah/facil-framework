"""
Repository for service_requests table.
Data access layer following 3-tier architecture.
"""
import asyncpg
from datetime import datetime
from typing import Optional, List, Dict, Any
from uuid import UUID
import json


class ServiceRequestRepository:
    """Data access layer for service_requests table"""

    # Workflows dont la BD (migration 291, trigger fn_enforce_bundle_sr_integrity)
    # exige commercial_license_id + fiscal_year NOT NULL à l'INSERT.
    _BUNDLE_WORKFLOW_CODES = frozenset({"BUNDLE_PAYMENT", "FIELD_INSPECTION"})

    async def create(
        self,
        db: asyncpg.Connection,
        user_id: UUID,
        workflow_code: str,
        solicitud_type: str = "expedicion",
        fiscal_service_id: Optional[int] = None,
        priority: str = "NORMAL",
        form_data: Optional[Dict] = None,
        batch_id: Optional[UUID] = None,
        company_id: Optional[UUID] = None,
        entity_code: Optional[str] = None,
        entity_location_id: Optional[UUID] = None,
        *,
        commercial_license_id: Optional[UUID] = None,
        fiscal_year: Optional[int] = None,
        bundle_id: Optional[UUID] = None,
        zone_id: Optional[UUID] = None,
        source: Optional[str] = None,
    ) -> Dict:
        """
        Create new service request.

        Reference is auto-generated by DB trigger trg_sr_auto_reference (migration 020).
        For BUNDLE_PAYMENT / FIELD_INSPECTION workflows, commercial_license_id and
        fiscal_year MUST be provided (enforced by trg_enforce_bundle_sr_integrity,
        migration 291). This method validates them fail-fast before hitting the DB
        to surface a clear error code to callers.

        :raises ValueError: BUNDLE_SR_MISSING_LICENSE_ID or BUNDLE_SR_MISSING_FISCAL_YEAR
            when a bundle workflow is created without the required bundle fields.
        """
        if workflow_code in self._BUNDLE_WORKFLOW_CODES:
            if commercial_license_id is None:
                raise ValueError("BUNDLE_SR_MISSING_LICENSE_ID")
            if fiscal_year is None:
                raise ValueError("BUNDLE_SR_MISSING_FISCAL_YEAR")

        query = """
            INSERT INTO service_requests (
                user_id, workflow_code, solicitud_type,
                fiscal_service_id, priority, form_data, created_by,
                batch_id, company_id, entity_code, entity_location_id,
                commercial_license_id, fiscal_year, bundle_id, zone_id,
                source
            )
            VALUES (
                $1, $2, $3,
                $4, $5, $6::jsonb, $1,
                $7, $8, $9, $10,
                $11, $12, $13, $14,
                COALESCE($15, 'citizen_wizard')
            )
            RETURNING *
        """
        row = await db.fetchrow(
            query,
            user_id,
            workflow_code,
            solicitud_type,
            fiscal_service_id,
            priority,
            json.dumps(form_data) if form_data else '{}',
            batch_id,
            company_id,
            entity_code,
            entity_location_id,
            commercial_license_id,
            fiscal_year,
            bundle_id,
            zone_id,
            source,
        )
        return self._row_to_dict(row)

    async def find_by_id(
        self,
        db: asyncpg.Connection,
        request_id: UUID
    ) -> Optional[Dict]:
        """Find service request by ID"""
        query = "SELECT * FROM service_requests WHERE id = $1"
        row = await db.fetchrow(query, request_id)
        return self._row_to_dict(row) if row else None

    async def find_by_reference(
        self,
        db: asyncpg.Connection,
        reference: str
    ) -> Optional[Dict]:
        """Find service request by reference (e.g., RES-2025-00001)"""
        query = "SELECT * FROM service_requests WHERE reference = $1"
        row = await db.fetchrow(query, reference)
        return self._row_to_dict(row) if row else None

    def _build_user_filters(
        self,
        user_id: UUID,
        status: Optional[str] = None,
        workflow_code: Optional[str] = None,
        category: Optional[str] = None,
        search: Optional[str] = None,
        date_from: Optional[str] = None,
        date_to: Optional[str] = None,
    ) -> tuple:
        """Build WHERE clause + params for user queries.
        Returns (where_str, params_list, next_param_idx)."""
        conditions = ["user_id = $1"]
        params: List[Any] = [user_id]
        idx = 2

        if status:
            conditions.append(f"status = ${idx}")
            params.append(status)
            idx += 1

        if workflow_code:
            conditions.append(f"workflow_code = ${idx}")
            params.append(workflow_code)
            idx += 1
        elif category:
            codes = self._get_codes_for_category(category)
            if codes:
                conditions.append(f"workflow_code = ANY(${idx})")
                params.append(codes)
                idx += 1

        if search:
            conditions.append(f"(reference ILIKE ${idx} OR workflow_code ILIKE ${idx})")
            params.append(f"%{search}%")
            idx += 1

        if date_from:
            conditions.append(f"created_at >= ${idx}::timestamptz")
            params.append(date_from)
            idx += 1

        if date_to:
            conditions.append(f"created_at < (${idx}::date + interval '1 day')")
            params.append(date_to)
            idx += 1

        return " AND ".join(conditions), params, idx

    def _get_codes_for_category(self, category: str) -> List[str]:
        """Get all workflow codes for a category from WorkflowEngine registry."""
        try:
            from ..services.workflow_engine import workflow_engine
            from ..models.enums import WorkflowCategory
            cat = WorkflowCategory(category)
            workflows = workflow_engine.get_workflows_by_category(cat)
            codes: List[str] = []
            for w in workflows:
                codes.extend([c.value for c in w.get_all_workflow_codes()])
            return codes
        except (ValueError, Exception):
            return []

    async def find_by_user(
        self,
        db: asyncpg.Connection,
        user_id: UUID,
        status: Optional[str] = None,
        workflow_code: Optional[str] = None,
        category: Optional[str] = None,
        search: Optional[str] = None,
        date_from: Optional[str] = None,
        date_to: Optional[str] = None,
        limit: int = 20,
        offset: int = 0
    ) -> List[Dict]:
        """List service requests for a user with full server-side filters"""
        where_clause, params, idx = self._build_user_filters(
            user_id, status, workflow_code, category, search, date_from, date_to
        )
        params.extend([limit, offset])

        query = f"""
            SELECT * FROM service_requests
            WHERE {where_clause}
            ORDER BY created_at DESC
            LIMIT ${idx} OFFSET ${idx + 1}
        """
        rows = await db.fetch(query, *params)
        return [self._row_to_dict(row) for row in rows]

    async def count_by_user(
        self,
        db: asyncpg.Connection,
        user_id: UUID,
        status: Optional[str] = None,
        workflow_code: Optional[str] = None,
        category: Optional[str] = None,
        search: Optional[str] = None,
        date_from: Optional[str] = None,
        date_to: Optional[str] = None,
    ) -> int:
        """Count service requests for a user with same filters as find_by_user"""
        where_clause, params, _ = self._build_user_filters(
            user_id, status, workflow_code, category, search, date_from, date_to
        )
        query = f"SELECT COUNT(*) FROM service_requests WHERE {where_clause}"
        row = await db.fetchrow(query, *params)
        return row["count"]

    async def update_status(
        self,
        db: asyncpg.Connection,
        request_id: UUID,
        new_status: str,
        performed_by: UUID,
        comment: Optional[str] = None
    ) -> Dict:
        """
        Update status and create history entry.
        Uses service_request_history table for audit trail.
        """
        # Get current status
        current = await self.find_by_id(db, request_id)
        if not current:
            raise ValueError(f"Service request {request_id} not found")

        # Update status (+ submitted_at when transitioning to SUBMITTED)
        if new_status == 'SUBMITTED':
            await db.execute(
                """UPDATE service_requests
                   SET status = $2, submitted_at = COALESCE(submitted_at, NOW()), updated_at = NOW()
                   WHERE id = $1""",
                request_id, new_status
            )
        else:
            await db.execute(
                """UPDATE service_requests
                   SET status = $2, updated_at = NOW()
                   WHERE id = $1""",
                request_id, new_status
            )

        # Create history entry
        await db.execute(
            """INSERT INTO service_request_history
               (service_request_id, action, previous_status, new_status,
                performed_by, comment)
               VALUES ($1, 'status_change', $2, $3, $4, $5)""",
            request_id, current["status"], new_status, performed_by, comment
        )

        return await self.find_by_id(db, request_id)

