@pytest_asyncio.fixture(scope="function")
async def conn():
    """Connection with outer transaction rollback — zero side effects on DB."""
    c = await asyncpg.connect(load_database_url())
    tr = c.transaction()
    await tr.start()
    try:
        yield c
    finally:
        await tr.rollback()
        await c.close()


@pytest_asyncio.fixture(scope="function")
async def bundle_fixture(conn):
    """Fetch a real commercial_license + owner user so we have a valid
    (license_id, fiscal_year, bundle_id, zone_id, user_id) tuple for tests.
    """
    lic = await conn.fetchrow(
        """
        SELECT id, company_id, bundle_id, zone_id, fiscal_year
        FROM commercial_licenses
        WHERE status IN ('open', 'overdue')
        LIMIT 1
        """
    )
    if not lic:
        pytest.skip("No payable commercial_license available for tests")

    owner = await conn.fetchrow(
        """
        SELECT u.id
        FROM user_company_roles ucr
        JOIN users u ON u.id = ucr.user_id
        WHERE ucr.company_id = $1
          AND ucr.role = 'company_owner'
          AND ucr.is_active = true
        LIMIT 1
        """,
        lic["company_id"],
    )
    if not owner:
        # Fallback: any citizen user (tests only need a valid user_id FK).
        owner = await conn.fetchrow(
            "SELECT id FROM users WHERE role = 'citizen' LIMIT 1"
        )
    if not owner:
        pytest.skip("No suitable user available")

    return {
        "license_id": lic["id"],
        "company_id": lic["company_id"],
        "bundle_id": lic["bundle_id"],
        "zone_id": lic["zone_id"],
        "fiscal_year": lic["fiscal_year"],
        "user_id": owner["id"],
    }


