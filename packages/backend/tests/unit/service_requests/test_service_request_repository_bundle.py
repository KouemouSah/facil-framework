# ═══════════════════════════════════════════════════════════════
# T6 — Partial UNIQUE index idx_sr_commercial_license_unique
#      prevents two bundle SRs pointing to the same license
# ═══════════════════════════════════════════════════════════════


async def test_create_bundle_payment_duplicate_license_raises_unique(
    conn, bundle_fixture
):
    repo = ServiceRequestRepository()

    # First INSERT must succeed
    first = await repo.create(
        db=conn,
        user_id=bundle_fixture["user_id"],
        workflow_code="BUNDLE_PAYMENT",
        form_data={},
        commercial_license_id=bundle_fixture["license_id"],
        fiscal_year=bundle_fixture["fiscal_year"],
        bundle_id=bundle_fixture["bundle_id"],
        zone_id=bundle_fixture["zone_id"],
    )
    assert first["id"] is not None

    # Second INSERT on the SAME commercial_license_id must be rejected
    # by the partial unique index idx_sr_commercial_license_unique.
    with pytest.raises(asyncpg.UniqueViolationError):
        await repo.create(
            db=conn,
            user_id=bundle_fixture["user_id"],
            workflow_code="BUNDLE_PAYMENT",
            form_data={},
            commercial_license_id=bundle_fixture["license_id"],
            fiscal_year=bundle_fixture["fiscal_year"],
            bundle_id=bundle_fixture["bundle_id"],
            zone_id=bundle_fixture["zone_id"],
        )
