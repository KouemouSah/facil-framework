# T1 — BUNDLE_PAYMENT with all required fields → INSERT succeeds
# ═══════════════════════════════════════════════════════════════


async def test_create_bundle_payment_with_all_fields_succeeds(conn, bundle_fixture):
    repo = ServiceRequestRepository()

    result = await repo.create(
        db=conn,
        user_id=bundle_fixture["user_id"],
        workflow_code="BUNDLE_PAYMENT",
        form_data={"license_id": str(bundle_fixture["license_id"])},
        company_id=bundle_fixture["company_id"],
        commercial_license_id=bundle_fixture["license_id"],
        fiscal_year=bundle_fixture["fiscal_year"],
        bundle_id=bundle_fixture["bundle_id"],
        zone_id=bundle_fixture["zone_id"],
    )

    assert result["id"] is not None
    assert result["workflow_code"] == "BUNDLE_PAYMENT"
    assert result["commercial_license_id"] == bundle_fixture["license_id"]
    assert result["fiscal_year"] == bundle_fixture["fiscal_year"]
    assert result["bundle_id"] == bundle_fixture["bundle_id"]
    assert result["zone_id"] == bundle_fixture["zone_id"]
    # source defaults to 'citizen_wizard' when not passed explicitly
    assert result["source"] == "citizen_wizard"
    # Auto-generated by trg_sr_auto_reference
    assert result["reference"] is not None
    assert len(result["reference"]) > 0


