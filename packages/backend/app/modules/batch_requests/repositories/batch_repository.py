"""
Data access layer for batch_requests and batch_request_items tables.
Uses asyncpg parameterized queries ($1, $2, ...).
"""
import json
import math
from typing import Optional, List, Dict, Any
from uuid import UUID

import asyncpg
from loguru import logger

# Maximum beneficiaries per batch — configurable via env var (B-021)
import os
MAX_BENEFICIARIES_PER_BATCH = int(os.environ.get("BATCH_MAX_BENEFICIARIES", "500"))


class BatchRepository:
    """Repository for batch_requests CRUD operations."""

    # =========================================================================
    # BATCH REQUESTS
    # =========================================================================

    async def create_batch(
        self,
        db: asyncpg.Connection,
        submitted_by: UUID,
        workflow_code: str,
        solicitud_type: str = "expedicion",
        company_id: Optional[UUID] = None,
        entity_code: Optional[str] = None,
        notes: Optional[str] = None,
    ) -> Optional[Dict]:
        """Create a new batch request. Reference is auto-generated by trigger."""
        query = """
            INSERT INTO batch_requests (
                submitted_by, workflow_code, solicitud_type,
                company_id, entity_code, notes
            )
            VALUES ($1, $2, $3, $4, $5, $6)
            RETURNING *
        """
        row = await db.fetchrow(
            query,
            submitted_by,
            workflow_code,
            solicitud_type,
            company_id,
            entity_code,
            notes,
        )
        return dict(row) if row else None

    async def find_batch_by_id(
        self,
        db: asyncpg.Connection,
        batch_id: UUID,
    ) -> Optional[Dict]:
        """Find batch request by ID."""
        query = "SELECT * FROM batch_requests WHERE id = $1"
        row = await db.fetchrow(query, batch_id)
        return dict(row) if row else None

    async def find_batch_by_reference(
        self,
        db: asyncpg.Connection,
        reference: str,
    ) -> Optional[Dict]:
        """Find batch request by reference (LOT-YYYY-NNNNN)."""
        query = "SELECT * FROM batch_requests WHERE reference = $1"
        row = await db.fetchrow(query, reference)
        return dict(row) if row else None

    async def list_batches_by_user(
        self,
        db: asyncpg.Connection,
        user_id: UUID,
        status: Optional[str] = None,
        page: int = 1,
        page_size: int = 20,
    ) -> Dict:
        """List batch requests for a user with pagination."""
        conditions = ["submitted_by = $1"]
        params: List[Any] = [user_id]
        idx = 2

        if status:
            conditions.append(f"status = ${idx}")
            params.append(status)
            idx += 1

        where_clause = " AND ".join(conditions)

        # Count total
        count_query = f"SELECT COUNT(*) FROM batch_requests WHERE {where_clause}"
        total = await db.fetchval(count_query, *params)

        # Fetch page
        offset = (page - 1) * page_size
        data_query = f"""
            SELECT * FROM batch_requests
            WHERE {where_clause}
            ORDER BY created_at DESC
            LIMIT ${idx} OFFSET ${idx + 1}
        """
        params.extend([page_size, offset])
        rows = await db.fetch(data_query, *params)

        return {
            "batches": [dict(r) for r in rows],
            "total": total,
            "page": page,
            "page_size": page_size,
            "total_pages": math.ceil(total / page_size) if total > 0 else 0,
        }

    async def update_batch_status(
        self,
        db: asyncpg.Connection,
        batch_id: UUID,
        status: str,
    ) -> Optional[Dict]:
        """Update batch status."""
        query = """
            UPDATE batch_requests SET status = $2, updated_at = NOW()
            WHERE id = $1 RETURNING *
        """
        row = await db.fetchrow(query, batch_id, status)
        return dict(row) if row else None

    async def update_batch(
        self,
        db: asyncpg.Connection,
        batch_id: UUID,
        **kwargs,
    ) -> Optional[Dict]:
        """Update batch fields dynamically."""
        if not kwargs:
            return await self.find_batch_by_id(db, batch_id)

        allowed_fields = {
            "notes", "entity_code", "shared_documents",
            "per_item_amount", "total_amount", "total_items",
            "items_ready", "items_submitted", "items_completed",
            "submitted_at", "completed_at", "gateway_transaction_id",
        }
        sets = []
        params: List[Any] = [batch_id]
        idx = 2

        jsonb_fields = {"shared_documents"}

        for field, value in kwargs.items():
            if field not in allowed_fields:
                continue
            if field in jsonb_fields:
                sets.append(f"{field} = ${idx}::jsonb")
                params.append(json.dumps(value) if isinstance(value, (list, dict)) else value)
            else:
                sets.append(f"{field} = ${idx}")
                params.append(value)
            idx += 1

        if not sets:
            return await self.find_batch_by_id(db, batch_id)

        sets.append("updated_at = NOW()")
        query = f"UPDATE batch_requests SET {', '.join(sets)} WHERE id = $1 RETURNING *"
        row = await db.fetchrow(query, *params)
        return dict(row) if row else None

    async def delete_batch(
        self,
        db: asyncpg.Connection,
        batch_id: UUID,
    ) -> bool:
        """Delete a batch request (cascades to items)."""
        query = "DELETE FROM batch_requests WHERE id = $1"
        result = await db.execute(query, batch_id)
        return result == "DELETE 1"

