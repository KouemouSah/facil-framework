    async def add_item(
        self,
        db: asyncpg.Connection,
        batch_id: UUID,
        beneficiary_name: str,
        beneficiary_identifier: Optional[str] = None,
        beneficiary_identifier_type: Optional[str] = None,
        beneficiary_email: Optional[str] = None,
        beneficiary_phone: Optional[str] = None,
        conditions: Optional[Dict] = None,
        item_order: Optional[int] = None,
    ) -> Dict:
        """Add a beneficiary item to a batch. INSERT + count update in transaction."""
        # Check limit before insert
        current_count = await db.fetchval(
            "SELECT total_items FROM batch_requests WHERE id = $1",
            batch_id,
        )
        if current_count is not None and current_count >= MAX_BENEFICIARIES_PER_BATCH:
            raise ValueError(
                f"Límite de {MAX_BENEFICIARIES_PER_BATCH} beneficiarios por lote alcanzado."
            )

        async with db.transaction():
            # Auto-compute item_order if not provided
            if item_order is None:
                max_order = await db.fetchval(
                    "SELECT COALESCE(MAX(item_order), -1) + 1 FROM batch_request_items WHERE batch_id = $1",
                    batch_id,
                )
                item_order = max_order

            query = """
                INSERT INTO batch_request_items (
                    batch_id, beneficiary_name, beneficiary_identifier,
                    beneficiary_identifier_type, beneficiary_email,
                    beneficiary_phone, conditions, item_order
                )
                VALUES ($1, $2, $3, $4, $5, $6, $7::jsonb, $8)
                RETURNING *
            """
            row = await db.fetchrow(
                query,
                batch_id,
                beneficiary_name,
                beneficiary_identifier,
                beneficiary_identifier_type,
                beneficiary_email,
                beneficiary_phone,
                json.dumps(conditions) if conditions else '{}',
                item_order,
            )
            # Update total_items count on parent batch (same transaction)
            await db.execute(
                "UPDATE batch_requests SET total_items = total_items + 1, updated_at = NOW() WHERE id = $1",
                batch_id,
            )
        return dict(row)

    async def add_items_bulk(
        self,
        db: asyncpg.Connection,
        batch_id: UUID,
        items: List[Dict],
    ) -> List[Dict]:
        """Add multiple beneficiary items at once in a single transaction."""
        # Check limit before inserts
        current_count = await db.fetchval(
            "SELECT total_items FROM batch_requests WHERE id = $1",
            batch_id,
        )
        if current_count is not None and current_count + len(items) > MAX_BENEFICIARIES_PER_BATCH:
            raise ValueError(
                f"Límite de {MAX_BENEFICIARIES_PER_BATCH} beneficiarios por lote. "
                f"Actual: {current_count}, intentando agregar: {len(items)}."
            )

        created = []
        async with db.transaction():
            # Get current max order
            max_order = await db.fetchval(
                "SELECT COALESCE(MAX(item_order), -1) FROM batch_request_items WHERE batch_id = $1",
                batch_id,
            )
            current_order = max_order + 1

            for item_data in items:
                order = item_data.get("item_order", current_order)
                query = """
                    INSERT INTO batch_request_items (
                        batch_id, beneficiary_name, beneficiary_identifier,
                        beneficiary_identifier_type, beneficiary_email,
                        beneficiary_phone, conditions, item_order
                    )
                    VALUES ($1, $2, $3, $4, $5, $6, $7::jsonb, $8)
                    RETURNING *
                """
                row = await db.fetchrow(
                    query,
                    batch_id,
                    item_data["beneficiary_name"],
                    item_data.get("beneficiary_identifier"),
                    item_data.get("beneficiary_identifier_type"),
                    item_data.get("beneficiary_email"),
                    item_data.get("beneficiary_phone"),
                    json.dumps(item_data.get("conditions", {})),
                    order,
                )
                created.append(dict(row))
                current_order += 1

            # Update total_items count (same transaction)
            await db.execute(
                "UPDATE batch_requests SET total_items = total_items + $2, updated_at = NOW() WHERE id = $1",
                batch_id,
                len(created),
            )
        return created

    async def find_item_by_id(
        self,
        db: asyncpg.Connection,
        item_id: UUID,
    ) -> Optional[Dict]:
        """Find a batch item by ID."""
        query = "SELECT * FROM batch_request_items WHERE id = $1"
