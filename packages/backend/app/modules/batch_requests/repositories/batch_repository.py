        allowed_fields = {
            "beneficiary_name", "beneficiary_identifier",
            "beneficiary_identifier_type", "beneficiary_email",
            "beneficiary_phone", "conditions", "required_documents",
            "assigned_documents", "form_data", "status",
            "item_amount", "validation_errors", "missing_documents",
            "service_request_id", "item_order",
        }
        sets = []
        params: List[Any] = [item_id]
        idx = 2

        jsonb_fields = {
            "conditions", "required_documents", "assigned_documents",
            "form_data", "validation_errors", "missing_documents",
        }

        for field, value in kwargs.items():
            if field not in allowed_fields:
                continue
            if field in jsonb_fields:
                sets.append(f"{field} = ${idx}::jsonb")
                params.append(json.dumps(value) if isinstance(value, (list, dict)) else value)
            else:
                sets.append(f"{field} = ${idx}")
